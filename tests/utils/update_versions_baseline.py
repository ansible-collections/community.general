"""Generate tests/versions_baseline.yml with the minimum OS versions the integration tests run on in CI."""

from __future__ import annotations

import argparse
import difflib
import re
import sys
import typing as t
from collections import defaultdict
from collections.abc import Iterable
from pathlib import Path

import yaml
from antsibull_nox.azp import get_ci_matrix  # type: ignore[import-not-found]

BASELINE_FILE = Path("tests/versions_baseline.yml")
AZP_CONFIG = Path(".azure-pipelines/azure-pipelines.yml")
GHA_NOX_WORKFLOW = Path(".github/workflows/nox.yml")
GHA_MATRIX_WORKFLOW = "ansible-community/antsibull-nox/.github/workflows/reusable-nox-matrix.yml"
GHA_MATRIX_FILTERS = ("min-ansible-core", "max-ansible-core", "include-tags", "exclude-tags")

ROLLING = "rolling"
HEADER = """\
# Generated by tests/utils/update_versions_baseline.py - do not edit.
# Regenerate with: nox -e update-versions-baseline
#
# Minimum versions on which the integration tests run in CI.
# The keys under "os" are values of ansible_facts.distribution.
"""

COMMUNITY_IMAGE = "quay.io/ansible-community/test-image:"
DOCKER_IMAGES = [
    (re.compile(r"alpine(\d)(\d+)"), "Alpine", r"\1.\2"),
    (re.compile(r"fedora(\d+)"), "Fedora", r"\1"),
    (re.compile(r"ubuntu(\d\d)(\d\d)"), "Ubuntu", r"\1.\2"),
    (re.compile(re.escape(COMMUNITY_IMAGE) + r"archlinux"), "Archlinux", ROLLING),
    (re.compile(re.escape(COMMUNITY_IMAGE) + r"debian-bookworm"), "Debian", "12"),
    (re.compile(re.escape(COMMUNITY_IMAGE) + r"debian-(\d+)-[a-z]+"), "Debian", r"\1"),
    (re.compile(re.escape(COMMUNITY_IMAGE) + r"opensuse-leap-(\d+\.\d+)"), "openSUSE Leap", r"\1"),
    (re.compile(re.escape(COMMUNITY_IMAGE) + r"opensuse-tumbleweed"), "openSUSE Tumbleweed", ROLLING),
]
# The ansible-test default container only provides Python versions, it is not an OS under test.
IGNORED_DOCKER_IMAGES = {"default"}
REMOTE_PLATFORMS = {
    "alpine": "Alpine",
    "fedora": "Fedora",
    "freebsd": "FreeBSD",
    "macos": "MacOSX",
    "rhel": "RedHat",
    "ubuntu": "Ubuntu",
}


def load_yaml(path: Path) -> t.Any:
    return yaml.safe_load(path.read_text(encoding="utf-8"))


def azp_session_names() -> set[str]:
    config = load_yaml(AZP_CONFIG)
    return {
        target["test"]
        for stage in config["stages"]
        for job in stage.get("jobs", [])
        for target in job.get("parameters", {}).get("targets", [])
    }


def gha_matrix_filters() -> list[dict[str, str]]:
    workflow = load_yaml(GHA_NOX_WORKFLOW)
    return [
        {name.replace("-", "_"): str(job["with"][name]) for name in GHA_MATRIX_FILTERS if name in job["with"]}
        for job in workflow["jobs"].values()
        if job.get("uses", "").startswith(f"{GHA_MATRIX_WORKFLOW}@")
    ]


def executed_sessions() -> Iterable[dict[str, t.Any]]:
    """Return the integration sessions that actually run in AZP or in GHA."""
    azp_names = azp_session_names()
    sessions = {
        session["name"]: session for session in get_ci_matrix().get("integration", []) if session["name"] in azp_names
    }
    for filters in gha_matrix_filters():
        for session in get_ci_matrix(**filters).get("integration", []):
            sessions[session["name"]] = session
    return sessions.values()


def docker_os_version(image: str) -> tuple[str, str] | None:
    if image in IGNORED_DOCKER_IMAGES:
        return None
    for regex, distribution, version in DOCKER_IMAGES:
        match = regex.fullmatch(image)
        if match:
            return distribution, match.expand(version)
    raise ValueError(f"Unknown docker image {image!r}, add it to DOCKER_IMAGES in {__file__}")


def remote_os_version(remote: str) -> tuple[str, str]:
    platform, version = remote.split("/", 1)
    if platform not in REMOTE_PLATFORMS:
        raise ValueError(f"Unknown remote platform {platform!r}, add it to REMOTE_PLATFORMS in {__file__}")
    return REMOTE_PLATFORMS[platform], version


def os_version(tag: str) -> tuple[str, str] | None:
    if tag.startswith("docker-"):
        return docker_os_version(tag.removeprefix("docker-"))
    if tag.startswith("remote-"):
        return remote_os_version(tag.removeprefix("remote-"))
    return None


def version_key(version: str) -> tuple[int, tuple[int, ...]]:
    if version == ROLLING:
        return 1, ()
    return 0, tuple(int(part) for part in version.split("."))


def minimum_os_versions(sessions: Iterable[dict[str, t.Any]]) -> dict[str, str]:
    versions: dict[str, set[str]] = defaultdict(set)
    for session in sessions:
        for tag in session.get("tags", []):
            found = os_version(tag)
            if found:
                distribution, version = found
                versions[distribution].add(version)
    return {
        distribution: min(versions[distribution], key=version_key)
        for distribution in sorted(versions, key=str.casefold)
    }


def render(os_versions: dict[str, str]) -> str:
    baseline = {"schema_version": 1, "os": os_versions}
    return HEADER + yaml.safe_dump(baseline, sort_keys=False, default_flow_style=False)


def check(content: str) -> int:
    current = BASELINE_FILE.read_text(encoding="utf-8") if BASELINE_FILE.exists() else ""
    if current == content:
        return 0
    sys.stdout.writelines(
        difflib.unified_diff(
            current.splitlines(keepends=True),
            content.splitlines(keepends=True),
            fromfile=f"{BASELINE_FILE} (current)",
            tofile=f"{BASELINE_FILE} (expected)",
        )
    )
    print(f"{BASELINE_FILE} is out of date, run: nox -e update-versions-baseline")
    return 1


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help=f"fail if {BASELINE_FILE} is out of date")
    args = parser.parse_args()

    content = render(minimum_os_versions(executed_sessions()))
    if args.check:
        return check(content)
    BASELINE_FILE.write_text(content, encoding="utf-8")
    print(f"Wrote {BASELINE_FILE}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
